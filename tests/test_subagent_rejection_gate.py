class TestSubagentPreFlightRejectionLogic(unittest.TestCase):
    """Unit tests for the pre-flight verification gate logic and self-rejection simulation."""

    def setUp(self):
        self.valid_prompt = """You are a context-isolated subagent operating under the DEAP Engineering Framework.

Role: Micro-Task Implementer
Subagent Type: code_modifier_worker
Repository Classification: UPSTREAM_SPEC_CORE_COMPILER
Target: scripts/dispatch_subagent.py

Mandatory Instructions:
1. Step 1: Execute `view_file` on `skills/feature-driven-implementation/SKILL.md` as your very first step before executing any file edits, commands, or tools.
2. Repository Scope: You are operating within classification `UPSTREAM_SPEC_CORE_COMPILER`. Maintain all repository invariants.
3. Micro-Task Scope: Focus exclusively on target `scripts/dispatch_subagent.py`.
4. Engineering Standards: Follow RED-GREEN-REFACTOR cycle discipline.
5. Defect Reporting: Record defects with `gh issue create` and `glab issue create`.

PROCEED
"""

    def test_valid_prompt_passes_preflight(self):
        """Verify compliant prompt passes pre-flight gate with no rejection."""
        passed, reason = validate_subagent_preflight(self.valid_prompt)
        self.assertTrue(passed, f"Expected pass, got rejection: {reason}")
        self.assertEqual(reason, "")

    def test_empty_prompt_rejected(self):
        """Verify empty or whitespace prompt is rejected."""
        passed, reason = validate_subagent_preflight("")
        self.assertFalse(passed)
        self.assertTrue(reason.startswith("ERROR: Prompt rejected"))

        passed, reason = validate_subagent_preflight("   \n\t  ")
        self.assertFalse(passed)
        self.assertTrue(reason.startswith("ERROR: Prompt rejected"))

    def test_missing_view_file_on_skill_rejected(self):
        """Verify prompt missing view_file on SKILL.md is rejected."""
        prompt = """Role: Micro-Task Implementer
Repository Classification: UPSTREAM_SPEC_CORE_COMPILER
Target: FEAT-01
PROCEED
"""
        passed, reason = validate_subagent_preflight(prompt)
        self.assertFalse(passed)
        self.assertIn("ERROR: Prompt rejected", reason)
        self.assertIn("missing view_file directive on SKILL.md", reason)

    def test_missing_classification_rejected(self):
        """Verify prompt missing repository classification is rejected."""
        prompt = """Role: Micro-Task Implementer
Target: scripts/dispatch_subagent.py
1. Step 1: Execute `view_file` on `skills/feature-driven-implementation/SKILL.md` before taking actions.
PROCEED
"""
        passed, reason = validate_subagent_preflight(prompt)
        self.assertFalse(passed)
        self.assertIn("ERROR: Prompt rejected", reason)
        self.assertIn("missing repository classification", reason)

    def test_leading_line_level_steering_rejected(self):
        """Verify prompt with line-level code steering ahead of Step 1 is rejected."""
        prompt = """You are a subagent.
Repository Classification: UPSTREAM_SPEC_CORE_COMPILER
Target: scripts/dispatch_subagent.py

Replace line 40 with `DEFAULT_TYPE = "custom_worker"`.
Here is the code to apply:
```python
x = 1
```

Now execute:
1. Step 1: Execute `view_file` on `skills/feature-driven-implementation/SKILL.md` as your first step.
PROCEED
"""
        passed, reason = validate_subagent_preflight(prompt)
        self.assertFalse(passed)
        self.assertIn("ERROR: Prompt rejected", reason)
        self.assertIn("leading line-level steering detected", reason)

    def test_truncation_marker_rejected(self):
        """Verify prompt containing truncation markers like [...] or [summarized] is rejected."""
        prompt = """Repository Classification: UPSTREAM_SPEC_CORE_COMPILER
Role: Implementer [...]
1. Step 1: Execute `view_file` on `skills/feature-driven-implementation/SKILL.md`.
PROCEED
"""
        passed, reason = validate_subagent_preflight(prompt)
        self.assertFalse(passed)
        self.assertIn("ERROR: Prompt rejected", reason)
        self.assertIn("truncation/summarization detected", reason)

    def test_multi_item_scope_rejected(self):
        """Verify prompt targeting multiple features or batch mode is rejected."""
        prompt = """Repository Classification: UPSTREAM_SPEC_CORE_COMPILER
Role: Implementer
Target: FEAT-01 and FEAT-02
1. Step 1: Execute `view_file` on `skills/feature-driven-implementation/SKILL.md`.
PROCEED
"""
        passed, reason = validate_subagent_preflight(prompt)
        self.assertFalse(passed)
        self.assertIn("ERROR: Prompt rejected", reason)
        self.assertIn("micro-task scope violation", reason)

    def test_forbidden_issue_close_rejected(self):
        """Verify prompt containing issue closure commands is rejected."""
        prompt = """Repository Classification: UPSTREAM_SPEC_CORE_COMPILER
Role: Implementer
Target: FEAT-01
1. Step 1: Execute `view_file` on `skills/feature-driven-implementation/SKILL.md`.
Once finished, run `gh issue close 42`.
PROCEED
"""
        passed, reason = validate_subagent_preflight(prompt)
        self.assertFalse(passed)
        self.assertIn("ERROR: Prompt rejected", reason)
        self.assertIn("forbidden issue closure command", reason)


class TestDispatchSubagentPreFlightFidelity(unittest.TestCase):
    """Verifies that dispatch_subagent.py generates prompts conforming to the pre-flight gate."""

    def test_generated_prompt_passes_preflight_gate(self):
        """Verify prompts generated via generate_subagent_prompt pass pre-flight verification."""
        skill_path = os.path.join("skills", "feature-driven-implementation", "SKILL.md")
        target_path = os.path.join("scripts", "dispatch_subagent.py")

        prompt = generate_subagent_prompt(
            skill=skill_path,
            target=target_path,
            role="Feature Implementation Worker",
            subagent_type="code_modifier_worker",
            classification="UPSTREAM_SPEC_CORE_COMPILER",
            base_dir=PROJECT_ROOT,
        )

        passed, reason = validate_subagent_preflight(prompt)
        self.assertTrue(passed, f"Generated prompt failed pre-flight gate: {reason}")
        self.assertEqual(reason, "")


if __name__ == "__main__":
    unittest.main()
