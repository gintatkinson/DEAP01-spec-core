#!/usr/bin/env python3
"""
Unit tests for Subagent Self-Rejection Pre-Flight Gate.

Enforces that:
1. All agent definition templates under `.agents/agents/*/agent.md` declare the
   mandatory pre-flight verification gate verbatim.
2. Governance documents (`rules/subagent-dispatch-standards.md`, `AGENTS.md`, `.agents/AGENTS.md`)
   document and mandate the pre-flight verification gate and self-rejection armor.
3. The pre-flight verification logic strictly rejects non-compliant, summarized,
   or steered prompts with `ERROR: Prompt rejected`.
4. Canonical subagent prompts generated by `scripts/dispatch_subagent.py` pass the
   pre-flight gate with zero rejections.
"""

import glob
import os
import sys
import unittest

# Ensure repo root is on sys.path
TEST_DIR = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.abspath(os.path.join(TEST_DIR, ".."))
if PROJECT_ROOT not in sys.path:
    sys.path.insert(0, PROJECT_ROOT)

from scripts.lint_subagent_prompt import validate_subagent_preflight
from scripts.dispatch_subagent import generate_subagent_prompt


MANDATORY_PREFLIGHT_SENTENCE = (
    "Before taking any action, verify that your incoming prompt begins with the instruction "
    "to execute `view_file` on `SKILL.md` by exact path, contains the repository classification, "
    "and contains zero leading line-level steering. If invalid, halt immediately and emit "
    "`ERROR: Prompt rejected`."
)

EXPECTED_AGENT_ROLES = [
    "adversarial_auditor",
    "code_modifier_worker",
    "codebase_researcher",
    "feature_spec_writer",
    "validator_subagent",
    "spec_compliance_reviewer",
    "code_quality_reviewer",
]


class TestSubagentDefinitionArmor(unittest.TestCase):
    """Verifies that all agent definitions in .agents/agents/ enforce the pre-flight armor."""

    def setUp(self):
        self.agents_dir = os.path.join(PROJECT_ROOT, ".agents", "agents")

    def test_agents_directory_exists(self):
        """Verify that .agents/agents/ exists and contains agent definition subdirectories."""
        self.assertTrue(os.path.isdir(self.agents_dir), f"Directory missing: {self.agents_dir}")

    def test_all_expected_agent_roles_exist(self):
        """Verify that all core subagent roles have definition files in .agents/agents/."""
        for role in EXPECTED_AGENT_ROLES:
            role_file = os.path.join(self.agents_dir, role, "agent.md")
            self.assertTrue(
                os.path.isfile(role_file),
                f"Missing agent definition file for role '{role}': {role_file}",
            )

    def test_all_agent_definitions_contain_exact_preflight_check(self):
        """Verify that every agent.md contains the exact mandatory pre-flight sentence."""
        pattern = os.path.join(self.agents_dir, "*", "agent.md")
        agent_files = glob.glob(pattern)
        self.assertGreater(len(agent_files), 0, "No agent.md files found in .agents/agents/*/")

        for agent_file in agent_files:
            rel_path = os.path.relpath(agent_file, PROJECT_ROOT)
            with open(agent_file, "r", encoding="utf-8") as f:
                content = f.read()

            self.assertIn(
                MANDATORY_PREFLIGHT_SENTENCE,
                content,
                f"Agent definition '{rel_path}' missing exact pre-flight sentence: {MANDATORY_PREFLIGHT_SENTENCE}",
            )
            self.assertIn(
                "ERROR: Prompt rejected",
                content,
                f"Agent definition '{rel_path}' missing 'ERROR: Prompt rejected' emission token.",
            )

    def test_agent_definitions_have_step1_skill_read(self):
        """Verify that every agent definition instructs Step 1 view_file on SKILL.md."""
        pattern = os.path.join(self.agents_dir, "*", "agent.md")
        agent_files = glob.glob(pattern)

        for agent_file in agent_files:
            rel_path = os.path.relpath(agent_file, PROJECT_ROOT)
            with open(agent_file, "r", encoding="utf-8") as f:
                content = f.read()

            self.assertIn("view_file", content, f"'{rel_path}' missing view_file directive")
            self.assertIn("SKILL.md", content, f"'{rel_path}' missing SKILL.md reference")


