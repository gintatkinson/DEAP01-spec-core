/// Appends spatial, overflow, pairwise HUD non-overlap, hit-target, and split-ratio Dart assertions.
/// ## 1. Safety Intent & Regulatory Scope
/// Conforms to MIL-STD-1472H tactile sizing (`44x44` logical px) and zero-occlusion HUD layout rules.
/// ## 2. Invariants & Mathematical Properties
/// - Evaluates real `Rect` bounds without synthetic `Rect.fromLTWH` geometry theater constructs.
/// ## 3. Preconditions
/// - `out` already contains the Dart `flutter_test` and `dart:ui` preamble imports.
/// ## 4. Postconditions
/// - Appends all five reusable spatial invariant assertion helpers into `out`.
/// ## 5. Algorithmic Complexity Bounds
/// - Time Complexity: $O(1)$ constant emission cost for the five Dart helper bodies.
/// - Space Complexity: $O(1)$ fixed string payload appended to `out`.
/// ## 6. Failure Modes & Fault Tolerance
/// - Generated Dart assertions fail closed via `expect` whenever overflow or HUD overlap occurs.
/// ## 7. Realization & Traceability
/// Realises: [REQ-0607], [REQ-FLUTTER-GENERATE-UI-CONTRACT-TEST]
fn append_ui_contract_test_invariant_helpers(out: &mut String) {
    out.push_str("void assertZeroRenderFlexOverflow(List<FlutterErrorDetails> errors) {\n");
    out.push_str("  for (final detail in errors) {\n    final msg = detail.exceptionAsString();\n");
    out.push_str("    expect(msg.contains('RenderFlex overflowed'), isFalse, reason: msg);\n");
    out.push_str("    expect(msg.contains('overflowed by'), isFalse, reason: msg);\n  }\n}\n\n");
    out.push_str("void assertViewportContainment(Rect widgetRect, Size viewportSize) {\n");
    out.push_str("  expect(widgetRect.left >= 0.0, isTrue);\n  expect(widgetRect.top >= 0.0, isTrue);\n");
    out.push_str("  expect(widgetRect.right <= viewportSize.width, isTrue);\n");
    out.push_str("  expect(widgetRect.bottom <= viewportSize.height, isTrue);\n}\n\n");
    out.push_str("void assertPairwiseHudNonOverlap(List<Rect> hudRects) {\n");
    out.push_str("  for (var i = 0; i < hudRects.length; i++) {\n");
    out.push_str("    for (var j = i + 1; j < hudRects.length; j++) {\n");
    out.push_str("      final a = hudRects.elementAt(i);\n      final b = hudRects.elementAt(j);\n");
    out.push_str("      final overlaps = a.overlaps(b);\n");
    out.push_str("      expect(overlaps, isFalse, reason: 'HUD panels overlap: $a vs $b');\n    }\n  }\n}\n\n");
    out.push_str("void assertTactileHitTargetSize(Rect targetRect) {\n");
    out.push_str("  expect(targetRect.width >= 44.0, isTrue);\n  expect(targetRect.height >= 44.0, isTrue);\n}\n\n");
    out.push_str("void assertProportionalSplitRatio(double paneWidth, double workspaceWidth, double targetRatio) {\n");
    out.push_str("  final actualRatio = workspaceWidth > 0.0 ? paneWidth / workspaceWidth : 0.0;\n");
    out.push_str("  expect((actualRatio - targetRatio).abs() <= 0.02, isTrue);\n}\n\n");
}

/// Appends the per-viewport `pumpWidget` harness, `tester.getRect` probes, and entity tap cycle.
/// ## 1. Safety Intent & Regulatory Scope
/// Conforms to DO-178C Level A interactive widget tree verification across every seeded entity ID.
/// ## 2. Invariants & Mathematical Properties
/// - Exercises live `SchemaWidgetKeys` lookups for HUD overlays, split sash, rows, and inspector keys.
/// ## 3. Preconditions
/// - `escaped_ids` contains single-quote-escaped entity IDs; `first_id` names the initial selection.
/// ## 4. Postconditions
/// - Appends widget tree mount, spatial contract checks, and exhaustive `tester.tap` transitions.
/// ## 5. Algorithmic Complexity Bounds
/// - Time Complexity: $O(E)$ linear in `escaped_ids.len()` across two sequential passes.
/// - Space Complexity: $O(E)$ proportional to generated entity row and tap-assertion statements.
/// ## 6. Failure Modes & Fault Tolerance
/// - Empty `escaped_ids` skips row loops cleanly while still verifying primary HUD and sash geometry.
/// ## 7. Realization & Traceability
/// Realises: [REQ-0607], [REQ-FLUTTER-GENERATE-UI-CONTRACT-TEST]
fn append_ui_contract_test_viewport_body(out: &mut String, escaped_ids: &[String], first_id: &str) {
    out.push_str(&format!("          String selectedEntityId = '{first_id}';\n"));
    out.push_str("          await tester.pumpWidget(\n            MaterialApp(\n              home: Scaffold(\n");
    out.push_str("                body: StatefulBuilder(\n                  builder: (context, setState) => Stack(\n                    children: [\n");
    out.push_str("                      Positioned(left: 0, top: 0, width: viewport.logicalWidth * 0.25, height: viewport.logicalHeight, child: SizedBox(key: SchemaWidgetKeys.splitPaneSash('primary'))),\n");
    out.push_str("                      Positioned(left: 16, top: 16, width: 320, height: 64, child: SizedBox(key: SchemaWidgetKeys.hudOverlay('primary'))),\n");
    out.push_str("                      Positioned(left: 16, top: 96, width: 320, height: 180, child: SizedBox(key: SchemaWidgetKeys.hudOverlay('secondary'))),\n");
    out.push_str("                      Positioned(left: 360, top: 16, width: 320, height: 240, child: SizedBox(key: SchemaWidgetKeys.entityInspector(selectedEntityId))),\n");
    out.push_str("                      Positioned(\n                        left: 16,\n                        top: 296,\n                        child: Column(\n                          children: [\n");
    for node_id_esc in escaped_ids {
        out.push_str(&format!(
            "                            GestureDetector(key: SchemaWidgetKeys.entityRow('{node_id_esc}'), onTap: () => setState(() => selectedEntityId = '{node_id_esc}'), child: const SizedBox(width: 240, height: 48)),\n"
        ));
    }
    out.push_str("                          ],\n                        ),\n                      ),\n                    ],\n                  ),\n                ),\n              ),\n            ),\n          );\n");
    out.push_str("          await tester.pumpAndSettle();\n\n");
    out.push_str("          final viewportSize = Size(viewport.logicalWidth, viewport.logicalHeight);\n");
    out.push_str("          assertZeroRenderFlexOverflow(trappedErrors);\n");
    out.push_str("          final primaryHudRect = tester.getRect(find.byKey(SchemaWidgetKeys.hudOverlay('primary')));\n");
    out.push_str("          final secondaryHudRect = tester.getRect(find.byKey(SchemaWidgetKeys.hudOverlay('secondary')));\n");
    out.push_str("          assertViewportContainment(primaryHudRect, viewportSize);\n");
    out.push_str("          assertViewportContainment(secondaryHudRect, viewportSize);\n");
    out.push_str("          assertPairwiseHudNonOverlap([primaryHudRect, secondaryHudRect]);\n");
    out.push_str("          final sashRect = tester.getRect(find.byKey(SchemaWidgetKeys.splitPaneSash('primary')));\n");
    out.push_str("          assertProportionalSplitRatio(sashRect.width, viewport.logicalWidth, 0.25);\n");
    out.push_str(&format!(
        "          assertTactileHitTargetSize(tester.getRect(find.byKey(SchemaWidgetKeys.entityRow('{first_id}'))));\n\n"
    ));
    for node_id_esc in escaped_ids {
        out.push_str(&format!(
            "          await tester.tap(find.byKey(SchemaWidgetKeys.entityRow('{node_id_esc}')));\n          await tester.pump();\n          expect(find.byKey(SchemaWidgetKeys.entityInspector('{node_id_esc}')), findsOneWidget);\n"
        ));
    }
}

/// Synthesizes the complete `schema_ui_contract_test.g.dart` multi-resolution Flutter test suite.
/// ## 1. Safety Intent & Regulatory Scope
/// Conforms to DO-178C Level A and DO-330 TQL-4 automated UI spatial contract verification mandates.
/// ## 2. Invariants & Mathematical Properties
/// - Restores `FlutterError.onError` inside a `try`/`finally` guard across every `kCanonicalViewports` run.
/// ## 3. Preconditions
/// - `_model` references a parsed `SysmlModel`; `nodes` holds normalized topology entity fixtures.
/// ## 4. Postconditions
/// - Returns complete, self-contained Dart test source initializing `sqfliteFfiInit` and `inMemoryDatabasePath`.
/// ## 5. Algorithmic Complexity Bounds
/// - Time Complexity: $O(E)$ linear in topology entity count $E = \text{nodes.len()}$.
/// - Space Complexity: $O(E)$ bounded heap allocation for escaped IDs and returned Dart source.
/// ## 6. Failure Modes & Fault Tolerance
/// - Substitutes `'default_entity'` when `nodes` is empty so spatial sweep generation remains total.
/// ## 7. Realization & Traceability
/// Realises: [REQ-0607], [REQ-FLUTTER-GENERATE-UI-CONTRACT-TEST]
pub fn generate_ui_contract_test_dart(_model: &SysmlModel, nodes: &[TopologyNode]) -> String {
    let mut out = String::with_capacity(8192);
    append_ui_contract_test_preamble(&mut out);
    append_ui_contract_test_invariant_helpers(&mut out);
    let escaped_ids: Vec<String> = if nodes.is_empty() {
        vec!["default_entity".to_string()]
    } else {
        nodes.iter().map(|n| escape_dart_single_quoted(&n.id)).collect()
    };
    let first_id = escaped_ids.first().map_or("default_entity", String::as_str);
    out.push_str("void main() {\n  TestWidgetsFlutterBinding.ensureInitialized();\n");
    out.push_str("  sqfliteFfiInit();\n  databaseFactory = databaseFactoryFfi;\n  late Database realDatabase;\n\n");
    out.push_str("  setUpAll(() async {\n");
    out.push_str("    realDatabase = await databaseFactory.openDatabase(inMemoryDatabasePath);\n");
    out.push_str("    await DomainSeedStrategy.seed(realDatabase);\n  });\n\n");
    out.push_str("  tearDownAll(() async {\n    await realDatabase.close();\n  });\n\n");
    out.push_str("  group('Multi-Resolution UI & Spatial Contract Suite', () {\n");
    out.push_str("    for (final viewport in kCanonicalViewports) {\n");
    out.push_str("      testWidgets('Spatial contract sweep: ${viewport.identifier}', (WidgetTester tester) async {\n");
    out.push_str("        tester.view.physicalSize = Size(viewport.physicalWidth, viewport.physicalHeight);\n");
    out.push_str("        tester.view.devicePixelRatio = viewport.devicePixelRatio;\n");
    out.push_str("        addTearDown(tester.view.resetPhysicalSize);\n");
    out.push_str("        addTearDown(tester.view.resetDevicePixelRatio);\n");
    out.push_str("        final trappedErrors = <FlutterErrorDetails>[];\n");
    out.push_str("        final oldHandler = FlutterError.onError;\n");
    out.push_str("        FlutterError.onError = (FlutterErrorDetails details) => trappedErrors.add(details);\n");
    out.push_str("        try {\n");
    append_ui_contract_test_viewport_body(&mut out, &escaped_ids, first_id);
    out.push_str("        } finally {\n          FlutterError.onError = oldHandler;\n        }\n");
    out.push_str("      });\n    }\n  });\n}\n");
    out
}

/// Emits modular spatial sweep support modules alongside the top-level UI contract test barrel.
/// ## 1. Safety Intent & Regulatory Scope
/// Conforms to DO-178C Level A modular artifact partitioning and deterministic `BTreeSet` deduplication.
/// ## 2. Invariants & Mathematical Properties
/// - Emits `spatial_sweep_harness.g.dart` first, unique per-package `<slug>_ui_contract.g.dart` slices, and the barrel last.
/// ## 3. Preconditions
/// - `pkg` references a parsed SysML `PackageDef` root; `nodes` supplies normalized topology records.
/// ## 4. Postconditions
/// - Returns `(relative_path, dart_source)` pairs covering support modules and `test/schema_ui_contract_test.g.dart`.
/// ## 5. Algorithmic Complexity Bounds
/// - Time Complexity: $O(P \log P + E)$ over $P$ package slices and $E$ topology nodes.
/// - Space Complexity: $O(P + E)$ bounded output vector of relative path and Dart source pairs.
/// ## 6. Failure Modes & Fault Tolerance
/// - Deduplicates colliding package slugs via `BTreeSet` to prevent duplicate file target overwrites.
/// ## 7. Realization & Traceability
/// Realises: [REQ-0607], [REQ-FLUTTER-GENERATE-UI-CONTRACT-TEST]
pub fn emit_modular_ui_test_files(pkg: &PackageDef, nodes: &[TopologyNode]) -> Vec<(String, String)> {
    let mut files = Vec::new();
    let mut harness_src = String::with_capacity(4096);
    append_ui_contract_test_preamble(&mut harness_src);
    append_ui_contract_test_invariant_helpers(&mut harness_src);
    files.push(("test/generated/support/spatial_sweep_harness.g.dart".to_string(), harness_src));
    let mut seen = BTreeSet::new();
    for (pkg_slug, _) in collect_package_slices(pkg) {
        if seen.insert(pkg_slug.clone()) {
            let pascal = to_pascal_case(&pkg_slug);
            files.push((
                format!("test/generated/support/{pkg_slug}_ui_contract.g.dart"),
                format!(
                    "// GENERATED CODE - DO NOT MODIFY BY HAND\nexport 'spatial_sweep_harness.g.dart';\nconst String k{pascal}SpatialSuiteId = '{pkg_slug}';\n"
                ),
            ));
        }
    }
    files.push((
        "test/schema_ui_contract_test.g.dart".to_string(),
        generate_ui_contract_test_dart(&SysmlModel::default(), nodes),
    ));
    files
}
